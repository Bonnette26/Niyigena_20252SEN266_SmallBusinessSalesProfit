
-- PHASE IV: RELATIONSHIP VALIDATION
-- Dataset: UCI Online Retail

-- 1. Check records with missing invoice numbers
SELECT COUNT(*) AS MISSING_INVOICE_NUMBERS
FROM STG_ONLINE_RETAIL_RAW
WHERE INVOICENO IS NULL;

-- 2. Check invoices associated with multiple calendar dates
SELECT COUNT(*) AS INVOICES_WITH_MULTIPLE_CALENDAR_DATES
FROM (
    SELECT INVOICENO
    FROM STG_ONLINE_RETAIL_RAW
    GROUP BY INVOICENO
    HAVING COUNT(DISTINCT TRUNC(
        TO_DATE(TRIM(INVOICEDATE), 'MM/DD/YYYY HH24:MI')
    )) > 1
);

-- 3. Check invoices associated with multiple customers
SELECT COUNT(*) AS INVOICES_WITH_MULTIPLE_CUSTOMERS
FROM (
    SELECT INVOICENO
    FROM STG_ONLINE_RETAIL_RAW
    WHERE INVOICENO IS NOT NULL
    GROUP BY INVOICENO
    HAVING COUNT(DISTINCT CUSTOMERID) > 1
);

-- 4. Document unresolved customer IDs
SELECT
    INVOICENO,
    COUNT(*) AS UNRESOLVED_CUSTOMER_ROWS
FROM STG_ONLINE_RETAIL_RAW
WHERE TRIM(CUSTOMERID) = '0'
GROUP BY INVOICENO
ORDER BY INVOICENO;
