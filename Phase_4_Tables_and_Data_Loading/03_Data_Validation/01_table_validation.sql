
-- PHASE IV: TABLE AND DATA VALIDATION
-- Project: Small Business Sales and Profit Tracking System
-- Dataset: UCI Online Retail

-- 1. Verify the total number of imported records
SELECT COUNT(*) AS TOTAL_RECORDS
FROM STG_ONLINE_RETAIL_RAW;

-- 2. Check missing values
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(*) - COUNT(STOCKCODE) AS MISSING_STOCKCODE,
    COUNT(*) - COUNT(CUSTOMERID) AS MISSING_CUSTOMERID,
    COUNT(*) - COUNT(DESCRIPTION) AS MISSING_DESCRIPTION
FROM STG_ONLINE_RETAIL_RAW;

-- 3. Check cancellation rows and negative quantities
SELECT
    COUNT(CASE WHEN UPPER(TRIM(INVOICENO)) LIKE 'C%' THEN 1 END)
        AS CANCELLATION_ROWS,
    COUNT(CASE WHEN TO_NUMBER(TRIM(QUANTITY)) < 0 THEN 1 END)
        AS NEGATIVE_QUANTITY_ROWS
FROM STG_ONLINE_RETAIL_RAW;

-- 4. Validate numeric values
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(CASE
        WHEN TRIM(QUANTITY) IS NOT NULL
         AND VALIDATE_CONVERSION(TRIM(QUANTITY) AS NUMBER) = 0
        THEN 1 END) AS INVALID_QUANTITY,
    COUNT(CASE
        WHEN TRIM(UNITPRICE) IS NOT NULL
         AND VALIDATE_CONVERSION(TRIM(UNITPRICE) AS NUMBER) = 0
        THEN 1 END) AS INVALID_UNITPRICE
FROM STG_ONLINE_RETAIL_RAW;

-- 5. Validate invoice dates
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(CASE
        WHEN VALIDATE_CONVERSION(
            TRIM(INVOICEDATE) AS DATE,
            'MM/DD/YYYY HH24:MI'
        ) = 0
        THEN 1 END) AS INVALID_DATES
FROM STG_ONLINE_RETAIL_RAW;
