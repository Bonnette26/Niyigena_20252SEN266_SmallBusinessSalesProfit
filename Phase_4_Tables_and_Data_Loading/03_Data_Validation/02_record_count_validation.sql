
-- PHASE IV: RECORD COUNT VALIDATION
-- Dataset: UCI Online Retail

-- Count all imported records
SELECT COUNT(*) AS TOTAL_IMPORTED_RECORDS
FROM STG_ONLINE_RETAIL_RAW;

-- Count distinct invoices
SELECT COUNT(DISTINCT INVOICENO) AS DISTINCT_INVOICES
FROM STG_ONLINE_RETAIL_RAW;

-- Count distinct products
SELECT COUNT(DISTINCT STOCKCODE) AS DISTINCT_PRODUCTS
FROM STG_ONLINE_RETAIL_RAW;

-- Count distinct customers
SELECT COUNT(DISTINCT CUSTOMERID) AS DISTINCT_CUSTOMERS
FROM STG_ONLINE_RETAIL_RAW;
