-- FILE: 01_create_tables.sql

-- 1. PRODUCTS TABLE
CREATE TABLE PRODUCTS (
    product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR2(100) NOT NULL,
    unit_price NUMBER(10,2) NOT NULL,
    quantity_in_stock NUMBER DEFAULT 0 NOT NULL,

    CONSTRAINT chk_product_price
    CHECK (unit_price >= 0),

    CONSTRAINT chk_product_stock
    CHECK (quantity_in_stock >= 0)
);

-- 2. SALES TABLE
CREATE TABLE SALES (
    sale_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id NUMBER NOT NULL,
    quantity_sold NUMBER NOT NULL,
    sale_date DATE DEFAULT SYSDATE,

    CONSTRAINT fk_sales_product
    FOREIGN KEY (product_id)
    REFERENCES PRODUCTS(product_id),

    CONSTRAINT chk_sales_quantity
    CHECK (quantity_sold > 0)
);

-- 3. EXPENSES TABLE
CREATE TABLE EXPENSES (
    expense_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_description VARCHAR2(200) NOT NULL,
    amount NUMBER(10,2) NOT NULL,
    expense_date DATE DEFAULT SYSDATE,

    CONSTRAINT chk_expense_amount
    CHECK (amount > 0)
);

-- 4. AUDIT_LOG TABLE
CREATE TABLE AUDIT_LOG (
    audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name VARCHAR2(30) NOT NULL,
    action_type VARCHAR2(10) NOT NULL,
    record_id NUMBER,
    changed_by VARCHAR2(100),
    change_date TIMESTAMP DEFAULT SYSTIMESTAMP,
    details VARCHAR2(4000)
);
